"""
Build and cache a PixelMap-focused probe features dictionary from
Bill Karsh's Neuropixels_probe_features JSON.

The cache (pixelmap_probe_features.json) is rebuilt from the source JSON
every time this module is imported, so it stays current when the source
is updated without any manual step.

Exposed module-level names
--------------------------
PROBE_FEATURES : dict[str, dict]
    Keyed by IMEC part number (e.g. "NP2003").  Each value has:
      SpikeGLX_probe_number  – legacy integer type used in old IMRO headers
      IMRO_format            – e.g. "imro_np2003"
      n_readouts_total       – total simultaneous readout channels (num_readout_channels)
      n_readouts_per_shank   – per-shank readout limit (channels_per_bank)
      n_sites_total          – total physical electrodes (total_electrodes)
      n_sites_per_shank      – electrodes per shank (electrodes_per_shank)
      probe_name             – human-readable description
      horizontal_pitch       – electrode horizontal pitch (µm)
      vertical_pitch         – electrode vertical pitch (µm)
      layout_geometry        – "staggered", "linear", etc.
      num_shanks             – number of shanks
      pixelmap_probe_type    – PixelMap internal type string, or None if unknown.

PROBE_TYPE_MAP : dict[str, list[str]]
    Maps each pixelmap_probe_type to the sorted list of part numbers that
    belong to it.

IMRO_FORMAT_TO_PROBE_TYPE : dict[str, str | None]
    Maps each known IMRO format string to a pixelmap_probe_type, or None
    when the format alone is ambiguous (imro_np1000 is shared by many families).

LEGACY_PROBE_TYPE_MAP : dict[str, list[int]]
    Maps each probe type to its known legacy SpikeGLX integer probe numbers,
    for parsing IMRO files generated by SpikeGLX < 20260115.

LEGACY_INT_TO_IMRO_FORMAT : dict[int, str]
    Maps each known legacy integer probe type to its IMRO format string.
"""

