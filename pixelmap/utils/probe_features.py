# ---------------------------------------------------------------------------
# SpikeGLX integer exceptions
# Part numbers for which int(part_number[2:]) does NOT equal the legacy
# SpikeGLX integer type written in IMRO headers.
# ---------------------------------------------------------------------------
_SPIKEGLIX_NUMBER_EXCEPTIONS: dict[str, int] = {
    # Standard NP 1.0: all report as type 0.
    "NP1000": 0,
    "NP1001": 0,
    # NHP short staggered: same ASIC as 1.0 → type 0.
    "NP1010": 0,
    "NP1011": 0,
    "NP1012": 0,
    "NP1013": 0,
    "NP1014": 0,
    # NHP short linear: also report as type 0 in legacy SpikeGLX.
    "NP1015": 0,
    "NP1016": 0,
    "NP1017": 0,
    # Phase-1 pilot probes (NP-prefix)
    "NP2000": 21,   # 2.0 single-shank Phase 1 → type 21
    "NP2010": 24,   # 2.0 four-shank  Phase 1 → type 24
    # Old PRB-prefix pilot part numbers
    "PRB_1_2_0480_2":  0,
    "PRB_1_4_0480_1":  0,
    "PRB_1_4_0480_1_C": 0,
    "PRB2_1_2_0640_0": 21,
    "PRB2_4_2_0640_0": 24,
}


def _spikeglix_probe_number(part_number: str) -> int:
    """Return the legacy SpikeGLX integer type for a given part number."""
    if part_number in _SPIKEGLIX_NUMBER_EXCEPTIONS:
        return _SPIKEGLIX_NUMBER_EXCEPTIONS[part_number]
    try:
        return int(part_number[2:])
    except ValueError:
        return 0  # Unknown format; treat as generic NP 1.0


# ---------------------------------------------------------------------------
# Build / cache
# ---------------------------------------------------------------------------

def _build(source_json_path: Path) -> dict:
    """Read Bill Karsh's JSON and return the PixelMap-focused dict."""
    with open(source_json_path) as f:
        raw = json.load(f)

    probes_raw = raw.get("neuropixels_probes", raw)

    result: dict = {}
    for pn, data in probes_raw.items():
        imro_fmt = data["imro_table_format_type"]
        n_shanks = int(data["num_shanks"])

        ptype = _PART_NUMBER_TO_PROBE_TYPE.get(pn)

        result[pn] = {
            "SpikeGLX_probe_number": _spikeglix_probe_number(pn),
            "IMRO_format":           imro_fmt,
            "n_readouts_total":      int(data["num_readout_channels"]),
            "n_readouts_per_shank":  int(data["channels_per_bank"]),
            "n_sites_total":         int(data["total_electrodes"]),
            "n_sites_per_shank":     int(data["electrodes_per_shank"]),
            "probe_name":            data["description"],
            "horizontal_pitch":      float(data["electrode_pitch_horz_um"]),
            "vertical_pitch":        float(data["electrode_pitch_vert_um"]),
            "layout_geometry":       data["electrode_layout_type"],
            "num_shanks":            n_shanks,
            "pixelmap_probe_type":   ptype,
        }
    return result


# ---------------------------------------------------------------------------
# Module-level initialisation
# ---------------------------------------------------------------------------

PROBE_FEATURES: dict = _build(_SOURCE_JSON)

# Write/refresh the cache
_CACHE_JSON.parent.mkdir(parents=True, exist_ok=True)
with open(_CACHE_JSON, "w") as _f:
    json.dump(PROBE_FEATURES, _f, indent=2)

# Build PROBE_TYPE_MAP: probe_type → sorted list of part numbers.
PROBE_TYPE_MAP: dict[str, list[str]] = {pt: [] for pt in _PROBE_TYPE_ORDER}
for _pn, _feat in PROBE_FEATURES.items():
    _pt = _feat["pixelmap_probe_type"]
    if _pt in PROBE_TYPE_MAP:
        PROBE_TYPE_MAP[_pt].append(_pn)
for _pt in PROBE_TYPE_MAP:
    PROBE_TYPE_MAP[_pt].sort()
